<?php declare(strict_types = 1);

namespace ShipMonk\Modulint\Baseline;

use ShipMonk\Modulint\Result;
use function array_unique;
use function array_values;
use function ksort;
use function sort;
use function str_repeat;
use function var_export;

final class BaselineGenerator
{

    public function generateFileContent(Result $result): string
    {
        $forbiddenDependencies = [];

        foreach ($result->forbiddenDependencyErrors as $sourceModuleName => $errorsByTargetModule) {
            foreach ($errorsByTargetModule as $targetModuleName => $errors) {
                foreach ($errors as $error) {
                    $forbiddenDependencies[$sourceModuleName][$targetModuleName][] = "{$error->sourcePath} -> {$error->dependencyPath}";
                }
            }
        }

        $uncoveredDependencies = [];

        foreach ($result->uncoveredDependencyErrors as $sourceModuleName => $errors) {
            foreach ($errors as $error) {
                $uncoveredDependencies[$sourceModuleName][] = "{$error->sourcePath} -> {$error->dependencyPath}";
            }
        }

        $unusedDependencies = [];

        foreach ($result->unusedDependencyErrors as $sourceModuleName => $errors) {
            foreach ($errors as $error) {
                $unusedDependencies[$sourceModuleName][] = $error->unusedDependency->name;
            }
        }

        $missingModules = [];

        foreach ($result->missingModuleErrors as $directory => $errors) {
            foreach ($errors as $error) {
                $missingModules[$directory][] = $error->filePath;
            }
        }

        $sections = '';

        if ($forbiddenDependencies !== []) {
            ksort($forbiddenDependencies);

            $rendered = '';

            foreach ($forbiddenDependencies as $sourceModuleName => $fingerprintsByTargetModule) {
                $rendered .= '        ' . var_export($sourceModuleName, true) . " => [\n";
                $rendered .= $this->renderStringListMap($fingerprintsByTargetModule, 3);
                $rendered .= "        ],\n";
            }

            $sections .= "    'forbiddenDependencies' => [\n{$rendered}    ],\n";
        }

        if ($uncoveredDependencies !== []) {
            $sections .= "    'uncoveredDependencies' => [\n" . $this->renderStringListMap($uncoveredDependencies, 2) . "    ],\n";
        }

        if ($unusedDependencies !== []) {
            $sections .= "    'unusedDependencies' => [\n" . $this->renderStringListMap($unusedDependencies, 2) . "    ],\n";
        }

        if ($missingModules !== []) {
            $sections .= "    'missingModules' => [\n" . $this->renderStringListMap($missingModules, 2) . "    ],\n";
        }

        return "<?php declare(strict_types = 1);\n\n"
            . "// Generated by `modulint --generate-baseline`, do not edit manually.\n\n"
            . "return [\n{$sections}];\n";
    }

    /**
     * @param array<string, list<string>> $map
     */
    private function renderStringListMap(
        array $map,
        int $level,
    ): string
    {
        ksort($map);

        $indent = str_repeat('    ', $level);
        $itemIndent = str_repeat('    ', $level + 1);
        $output = '';

        foreach ($map as $key => $values) {
            $values = array_values(array_unique($values));
            sort($values);

            $output .= $indent . var_export($key, true) . " => [\n";

            foreach ($values as $value) {
                $output .= $itemIndent . var_export($value, true) . ",\n";
            }

            $output .= "{$indent}],\n";
        }

        return $output;
    }

}
